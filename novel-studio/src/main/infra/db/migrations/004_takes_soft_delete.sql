-- ============================================================================
-- Novel Studio · 迁移 004 · takes 软删除
-- ============================================================================
-- 设计依据：
--   · docs/12 §8.1「任何 take 都不自动删除（除用户显式清理）」+ TakeList 的两种删除：
--       「移除」（软删：文件保留，可恢复）与「彻底删除」（硬删：删文件，不可恢复）
--   · docs/20 §4.5 `take:delete { takeId, hard? }`
--
-- 为什么必须加这一列而不是复用 flags：
--   `flags` 是**给用户看**的标记（TakeFlagsPanel 直接渲染它，docs/12 §10）。
--   把「已移除」塞进 flags，用户会在打标面板里看到一个自己没打过的标记，而且
--   「只显示含某标记的 take」的筛选会被它污染。软删除状态属于**存储层**，
--   与 books/chapters/canvas_lines 的 `deleted_at` 是同一件事，就该用同一列名。
--
-- 为什么是 ADD COLUMN 而不是改 001：
--   001_init.sql 是已发布迁移，hash 被钉住（改它会拒绝启动）——结构变更只能新增迁移。
--
-- 注意：本列只用于「软删的 take 不出现在列表里」。
--   目前**没有**「恢复 take」的 IPC 通道（契约里没有），所以软删之后要靠 SQL 或
--   未来新增的通道恢复；这一点已在 docs/91 §5.2.18 登记，不要在 UI 上承诺可恢复。
-- ============================================================================

ALTER TABLE takes ADD COLUMN deleted_at INTEGER;

-- 列表查询一律带 `deleted_at IS NULL`，按行取 take 是最热的查询
CREATE INDEX IF NOT EXISTS idx_takes_line_alive ON takes(line_id, deleted_at);
