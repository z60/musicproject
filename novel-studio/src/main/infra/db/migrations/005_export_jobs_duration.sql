-- ============================================================================
-- 005 · 导出任务行的章节元数据（`duration_ms`）
-- ============================================================================
-- 背景：`export_jobs` 每一行代表「一章的导出结果」，而 `ExportChapterResult`
-- （docs/15 §6 的导出报告）需要 **durationMs**（该章导出后的实际时长）：
-- 它在验收与「章间时长差」检查里都要用，但 001 的 `export_jobs` 没有这一列。
--
-- 为什么现在加而不是当时就写：001 是已发布、哈希冻结的迁移（docs/21 §5），
-- 改它会让所有已升级的库与代码对不上（`loadMigrations` 会直接报 hash 不符）。
-- 新列只能通过新迁移追加 —— 这是本仓库「发布即冻结」纪律的常规代价。
--
-- 另外两列（chapter_index / title）**不加**：它们能从 `chapters.seq` /
-- `chapters.title` 联表得到，冗余存一份只会产生「章节改名后报告还是旧名字」
-- 的不一致。报告要回答的是「这次导出的产物是什么样」，而序号与标题属于章节本身。
--
-- ---------------------------------------------------------------------------
-- 配套约定（代码侧，写在这里让读 schema 的人也能看到）
-- ---------------------------------------------------------------------------
-- 一次导出会在本表写两类行：
--   · **批量行**：`id = jobId`，`chapter_id IS NULL`，记录整批的状态、参数与产物；
--   · **章节行**：`id = "{jobId}#{chapterIndex}"`，`chapter_id` 指向该章。
-- 两者用「id 前缀」建立关系（`WHERE id = ? OR id LIKE '{jobId}#%'`）。
-- 为什么不用外键列：005 只加一列（见上），而按前缀聚合足够快 ——
-- 一次导出最多几百章，且 `idx_export_jobs_book` / `idx_export_jobs_hash` 已覆盖主要查询。
-- 报告组装（`export:report`）依赖这个约定，改动它要同时改 `export.service.ts`。
--
-- `status` 的取值与语义（DDL 里已有 CHECK）：
--   pending / running / succeeded / failed / skipped / interrupted
-- 其中 `skipped` = 参数未变且已有产物（幂等跳过），`failed` 行**不写** `output_path`。

ALTER TABLE export_jobs ADD COLUMN duration_ms INTEGER;
