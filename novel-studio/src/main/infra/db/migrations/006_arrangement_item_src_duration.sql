-- ---------------------------------------------------------------------------
-- 0006 · arrangement_items.src_duration_ms（自动对轨必须按「录音里选中的音频」排）
-- ---------------------------------------------------------------------------
--
-- 真机反馈：「自动对轨功能需要根据录音里选择的音频来排」。
--
-- 现象：在录音模块里给某一行换了成品（或重新导入音频后选了另一条 take），回到对轨
--       点「自动对轨」，时间线上的那一段**还是旧音频的长度** —— 尾巴被切掉一截
--       （实测：选中的音频 6919 ms，item 上仍是上一版 take 的 0–6300 ms）。
--
-- 根因（两件事叠加，缺一不成灾）：
--
--   1. 录音侧「设为成品」（take:setSelected）**复用同一个 voice_segments.id**，
--      只把 segments/{id}.wav 的内容换成新 take 的音频（见 docs/12 §8.1 与
--      take.service.ts 的 materializeSegment）。所以 arrangement_items.segment_id
--      不变，光看外键根本看不出「音频换了」。
--   2. 自动对轨刻意保留既有 item 的裁剪点 src_in_ms / src_out_ms
--      （理由正当：用户可能手工拖过边缘，重排不该把手调结果冲掉）。
--      于是换成品之后，item 上那对裁剪点仍然按**旧音频**在切新音频：
--      越界会被 shared/arrange/layout.ts 夹回 segment 时长内，所以不会报错，
--      只会安静地少切或多切 —— 最难发现的那一类。
--
-- 为什么不能靠「裁剪长度 != 音频时长」来判定：
--   用户手工拖过边缘时，两者本来就不相等。库里的两种状态完全同形，无法区分。
--
-- 于是记下**排布时依据的音频长度**（src_duration_ms）：
--
--   · src_duration_ms == 当前 voice_segments.duration_ms
--       → 这段裁剪仍属于当前音频，保留（手工微调不丢）；
--   · 不相等（含历史数据的默认 0 = 不知道）
--       → 音频换过了：丢掉旧裁剪，按**当前选中的音频**整段重排（src_in = 0,
--         src_out = 当前音频时长），这正是真机要的行为。
--
-- 只写不读的例外：updateItem / updateItems（用户手工拖裁剪）**不会**改这一列 ——
-- 它记的是「当时依据的音频」，不是「裁剪点」，改了就等于把音频变更伪装成没发生。
--
-- 该列只增不改：老库在迁移时统一落 0，代价是下一次自动对轨会按当前音频重排一次
-- （对已经跑偏的时间线来说，这恰好是我们想要的）。
ALTER TABLE arrangement_items ADD COLUMN src_duration_ms INTEGER NOT NULL DEFAULT 0;
