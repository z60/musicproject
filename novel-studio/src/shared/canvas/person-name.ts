/**
 * Novel Studio · 人名形态学（抽取精度的判别器）
 * ============================================================================
 * 设计依据：docs/11 §4.6（角色表「自动抽取」）、docs/06 §5.1 Step 3（角色名抽取）
 *
 * ### 为什么需要这个模块（真机事故 docs/91 §5.2.32）
 * 真机 94 章 / 122 万字抽取出来 230 个候选，绝大多数是**常用词**：
 * `开始(355)`、`上面(354)`、`尽管(245)`、`第二(153)`、`年人(147)`、`躬身(106)`、
 * `随口(74)`、`难道(58)`、`随后轻(29)`、`修神色(36)` …
 *
 * 它们的来源是「引导语窗口」的切片错误与「老X」称谓的误归并，而不是「出现次数少」——
 * 所以任何**按出现次数**的过滤都挡不住它们（`随口问道` 能命中 62 次）。
 * 能挡住的只有**形态证据**：
 *
 *   1. **姓氏**：`姜练 / 晏灵修 / 沈绪 / 景琼 / 白言书` 都以姓氏开头；
 *      `开始 / 上面 / 尽管 / 第二 / 躬身 / 随口` 都不是。
 *   2. **角色称谓**：`师尊 / 掌教 / 祖师 / 长老 / 护法` 这类是要分配配音员的**角色**，
 *      作为候选是合理的（它们本身不是人名，但用户确实需要给它们分配声音）。
 *   3. **句首主语位置**：真人名会反复出现在句首做主语（实测 39%~61% 的出现在句首），
 *      而 `开始 / 年人 / 躬身 / 随口 / 修神色` 在句首出现 **0 次**。
 *
 * 零第三方依赖：这里是静态字表，不引入分词器/大模型（用户明确选「零外部依赖」路线）。
 * 它只是**判别器**，不是 NER：只用来把「显然不是人的词」挡在候选之外，
 * 拿不准的一律放行（宁可多给，不可误杀 —— 详见 docs/91 §5.2.32 的取舍说明）。
 */

