/** 是否以常见姓氏开头（单字或复姓；含异体写法归一） */
export function startsWithSurname(token: string): boolean {
  const t = token.trim()
  if (t.length < 2) return false
  if (startsWithSurnameExact(t)) return true
  const [variant, standard] = pickSurnameVariant(t)
  if (variant === standard) return false
  return startsWithSurnameExact(standard + t.slice(1))
}

/** 严格按字表判断（不做异体归一），供内部与测试使用 */
export function startsWithSurnameExact(token: string): boolean {
  const t = token.trim()
  if (t.length < 2) return false
  for (const compound of COMPOUND_SURNAMES) {
    if (t.startsWith(compound)) return true
  }
  return SURNAMES.has(t[0]!)
}

/** 把首字的异体写法换成标准写法（没有异体则原样返回） */
export function normalizeSurname(token: string): string {
  const t = token.trim()
  if (t.length < 2) return t
  const [variant, standard] = pickSurnameVariant(t)
  return variant === standard ? t : standard + t.slice(1)
}

function pickSurnameVariant(token: string): readonly [string, string] {
  const first = token[0]!
  for (const pair of SURNAME_VARIANTS) {
    if (pair[0] === first) return pair
  }
  return [first, first]
}

/**
 * 音译/外来名形态特征字（`哈维尔 / 诺顿·阿兰 / 独眼多特 / 舍沙 / 沙加`）。
 *
 * 为什么需要它：姓氏表只覆盖汉名，**音译名一个都命中不了**（哈/维/尔 都不是姓氏），
 * 而它们确实是角色。音译名几乎必然含这批字（尔/斯/特/德/克/夫/娜/妮/丝/维/诺/姆/莉/塔/雷…），
 * 反过来说，`随口 / 躬身 / 尽管 / 开始 / 修神色 / 至于魔` 这些常见词里一个都没有。
 */
const TRANSLITERATION_CHARS = new Set(
  '哈维尔斯德克夫特娜妮丝诺姆莉塔雷恩蒂奇拉西卡巴亚加吉洛伊沙瓦迪罗托泰帕潘蕾玛琳达尼奥兰兹森瑟柏迈曼乔缇弗洛'.split(''),
)

/** 是否像音译名：带间隔号（`诺顿·阿兰`）或含音译特征字（长度 ≥2） */
export function looksLikeTransliteratedName(token: string): boolean {
  const t = token.trim()
  if (t.includes('·')) return t.length >= 3
  if (t.length < 2) return false
  for (const ch of t) if (TRANSLITERATION_CHARS.has(ch)) return true
  return false
}

/**
 * 是否是「角色称谓」表里的词（**精确匹配**，`晏掌教` 这类「名字 + 称谓」走别名归并）。
 *
 * 刻意不做后缀匹配：真机上 `拜见师尊`、`劳烦师尊`、`包括师尊` 这类动词短语都会命中后缀，
 * 让它们以「角色称谓」的身份混进候选（实测 `师尊` 名下挂了 60 多个这种垃圾别名）。
 */
export function isRoleTitle(token: string): boolean {
  const t = token.trim()
  return t.length >= 2 && ROLE_TITLES.includes(t)
}

/**
 * 是否是「老X / 小X / 大X / 阿X / X儿 / X兄 / X老」这类称谓写法。
 *
 * `X老`（`荒老 / 练老 / 药老`）与 `大X`（`大白猫`）是真机上漏掉过的两类：
 * 前者是最常见的「某老」称谓，后者是宠物/绰号的常见前缀。
 *
 * 刻意**不含** `X长老 / X大人 / X师兄 / X师尊` 这类「名字 + 尊称」：
 * 它们必须由抽取器找到正名后并成别名，否则 `拜见师尊`、`知道师尊` 这种动词短语会全部通过。
 */
export function looksLikeAppellation(token: string): boolean {
  const t = token.trim()
  if (t.length < 2) return false
  if (/^[老小大阿][\u4e00-\u9fa5]{1,2}$/.test(t)) return true
  return /^[\u4e00-\u9fa5](儿|兄|老)$/.test(t)
}
